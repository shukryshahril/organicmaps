#!/usr/bin/env python3
"""Generate the Java geoid table from the pinned, decoded AndroidX model.

The source is assets/database/geoid-height-map-v0.db in
androidx.core:core-location-altitude:1.0.1 (Apache-2.0). The SQLite asset has SHA-256
aa4f7a49d67ffd72df3c1e6ce3c2e8b5cd00d433f149591dae2ac25ff9b876d7.

Its six JPEG faces were decoded with libjpeg-turbo JDCT_ISLOW, then the PNG blue
channel corrections were added modulo 256. Runtime image decoding is deliberately
avoided: Android 5's decoder produces different samples from newer Android.

model.bin pins these numeric samples as 384 independent, lossless tiles. It has
an eight-byte magic, 384 little-endian uint16 stream lengths, and zlib streams.
Within each 64x64 tile, samples are predicted by left + up - upper-left, modulo
256. Reading and regenerating the Java source requires only Python's standard
library. --from-raw recreates model.bin from the six face-major 512x512 byte grids
when updating the reference model; update and review its metadata at that time.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
import zlib


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT = ROOT / "android/sdk/src/main/java/app/organicmaps/sdk/location/GeoidData.java"
MODEL = HERE / "model.bin"
METADATA = HERE / "model.json"
MAGIC = b"OMGEOID1"
FACES = 6
FACE_SIZE = 512
TILE_SIZE = 64
TILES_PER_FACE = FACE_SIZE // TILE_SIZE
TILE_COUNT = FACES * TILES_PER_FACE * TILES_PER_FACE
LENGTHS = struct.Struct(f"<{TILE_COUNT}H")


def tile_origins():
    for face in range(FACES):
        for row in range(0, FACE_SIZE, TILE_SIZE):
            for column in range(0, FACE_SIZE, TILE_SIZE):
                yield face, row, column


def validate_grid(grid, metadata):
    if len(grid) != FACES * FACE_SIZE * FACE_SIZE:
        raise ValueError("Expected six 512x512 byte grids")
    if hashlib.sha256(grid).hexdigest() != metadata["decoded_sha256"]:
        raise ValueError("Decoded model differs from the pinned reference")


def encode(grid):
    streams = []
    for face, row, column in tile_origins():
        residuals = bytearray()
        for y in range(TILE_SIZE):
            for x in range(TILE_SIZE):
                i = face * FACE_SIZE * FACE_SIZE + (row + y) * FACE_SIZE + column + x
                residuals.append((grid[i]
                                  - (grid[i - 1] if x else 0)
                                  - (grid[i - FACE_SIZE] if y else 0)
                                  + (grid[i - FACE_SIZE - 1] if x and y else 0)) & 255)
        streams.append(zlib.compress(residuals, 9))
    return streams


def read_model():
    source = MODEL.read_bytes()
    if source[:len(MAGIC)] != MAGIC:
        raise ValueError("Invalid geoid model header")
    lengths = LENGTHS.unpack_from(source, len(MAGIC))
    offset = len(MAGIC) + LENGTHS.size
    streams = []
    for length in lengths:
        streams.append(source[offset:offset + length])
        offset += length
    if offset != len(source) or any(not stream for stream in streams):
        raise ValueError("Invalid geoid tile lengths")
    return streams


def decode(streams):
    grid = bytearray(FACES * FACE_SIZE * FACE_SIZE)
    for stream, (face, row, column) in zip(streams, tile_origins()):
        tile = bytearray(zlib.decompress(stream))
        if len(tile) != TILE_SIZE * TILE_SIZE:
            raise ValueError("Invalid decoded tile size")
        for y in range(TILE_SIZE):
            for x in range(TILE_SIZE):
                i = y * TILE_SIZE + x
                tile[i] = (tile[i]
                           + (tile[i - 1] if x else 0)
                           + (tile[i - TILE_SIZE] if y else 0)
                           - (tile[i - TILE_SIZE - 1] if x and y else 0)) & 255
                grid[face * FACE_SIZE * FACE_SIZE + (row + y) * FACE_SIZE + column + x] = tile[i]
    return grid


def java_source(streams, metadata):
    lines = [
        "/*",
        " * Copyright 2022 The Android Open Source Project",
        " *",
        ' * Licensed under the Apache License, Version 2.0 (the "License");',
        " * you may not use this file except in compliance with the License.",
        " * You may obtain a copy of the License at",
        " *",
        " *      https://www.apache.org/licenses/LICENSE-2.0",
        " *",
        " * Unless required by applicable law or agreed to in writing, software",
        ' * distributed under the License is distributed on an "AS IS" BASIS,',
        " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        " * See the License for the specific language governing permissions and",
        " * limitations under the License.",
        " */",
        "",
        "package app.organicmaps.sdk.location;",
        "",
        "// Generated by tools/python/geoid/generate_geoid.py. Do not edit.",
        f'// Decoded model SHA-256: {metadata["decoded_sha256"]}',
        "final class GeoidData",
        "{",
        f'  static final double SCALE_METERS = {metadata["scale_meters"]};',
        f'  static final double OFFSET_METERS = {metadata["offset_meters"]};',
        f'  static final double RMSE_METERS = {metadata["rmse_meters"]};',
        "",
        "  private GeoidData() {}",
        "",
        "  // Factories allocate only the requested tile and keep each method below Java's size limit.",
        "  // clang-format off",
        "  static byte[] getTile(int tile)",
        "  {",
        "    return switch (tile)",
        "    {",
    ]
    for tile in range(len(streams)):
        lines.append(f"    case {tile} -> tile{tile}();")
    lines.extend([
        '    default -> throw new IndexOutOfBoundsException("Invalid geoid tile: " + tile);',
        "    };",
        "  }",
    ])
    for tile, stream in enumerate(streams):
        lines.extend([
            "",
            f"  private static byte[] tile{tile}()",
            "  {",
            "    return new byte[] {",
        ])
        for offset in range(0, len(stream), 16):
            values = (str(value if value < 128 else value - 256) for value in stream[offset:offset + 16])
            lines.append("      " + ", ".join(values) + ",")
        lines.extend(["    };", "  }"])
    lines.extend([
        "  // clang-format on",
        "}",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the generated Java file")
    parser.add_argument("--from-raw", type=Path, help="Recreate model.bin from a decoded byte grid")
    args = parser.parse_args()
    metadata = json.loads(METADATA.read_text())
    if args.from_raw:
        if args.check:
            parser.error("--check cannot be combined with --from-raw")
        grid = args.from_raw.read_bytes()
        validate_grid(grid, metadata)
        streams = encode(grid)
        MODEL.write_bytes(MAGIC + LENGTHS.pack(*(len(s) for s in streams)) + b"".join(streams))
    else:
        streams = read_model()
    validate_grid(decode(streams), metadata)
    generated = java_source(streams, metadata)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            sys.exit(f"Regenerate {OUTPUT.relative_to(ROOT)}")
    else:
        OUTPUT.write_text(generated)
    print(f"Verified {TILE_COUNT} tiles, {sum(map(len, streams))} compressed bytes")


if __name__ == "__main__":
    main()
